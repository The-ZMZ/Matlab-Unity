function response = TastePlacementResponse(foodRef, selectedCategory)
%TASTEPLACEMENTRESPONSE Build the MATLAB result for one taste placement.
%
%   The valid, correct, code and message fields match the fields used by the
%   existing PLACE_RES / ERROR protocol responses. The remaining fields are
%   MATLAB-side activity data used by progress tracking and diagnostics.

    validation = ValidateTasteAnswer(foodRef, selectedCategory);

    response = struct( ...
        'valid', validation.valid, ...
        'correct', validation.correct, ...
        'code', validation.code, ...
        'message', validation.message, ...
        'foodId', validation.foodId, ...
        'foodKey', validation.foodKey, ...
        'foodName', validation.foodName, ...
        'expectedCategory', validation.expectedCategory, ...
        'selectedCategory', validation.selectedCategory);
end
