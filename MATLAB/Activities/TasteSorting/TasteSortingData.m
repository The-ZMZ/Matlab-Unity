function data = TasteSortingData()
%TASTESORTINGDATA MATLAB-owned dataset for the Taste Classification activity.
%
%   data = TasteSortingData() returns the single reusable definition of the
%   eight foods, their stable identifiers, display names and correct taste
%   categories. Unity never receives the food-to-category mapping for
%   validation; it only uses the string keys as protocol object identifiers.
%
%   The dataset is validated on every call by ValidateTasteDataset, so a
%   missing, duplicated or malformed entry cannot be used silently.

    categories = ["Sweet", "Sour", "Bitter", "Salty"];

    ids = [1, 2, 3, 4, 5, 6, 7, 8];
    keys = [ ...
        "ice_cream", ...
        "lemon", ...
        "tomato", ...
        "garlic", ...
        "pizza", ...
        "coffee", ...
        "chips", ...
        "donuts"];
    names = [ ...
        "Ice Cream", ...
        "Lemon", ...
        "Tomato", ...
        "Garlic", ...
        "Pizza", ...
        "Coffee", ...
        "Chips", ...
        "Donuts"];
    foodCategories = [ ...
        "Sweet", ...
        "Sour", ...
        "Sour", ...
        "Bitter", ...
        "Salty", ...
        "Bitter", ...
        "Salty", ...
        "Sweet"];

    foods = repmat(struct( ...
        'id', 0, ...
        'key', "", ...
        'name', "", ...
        'category', "", ...
        'targetId', ""), 1, numel(ids));

    for k = 1:numel(ids)
        foods(k).id = ids(k);
        foods(k).key = keys(k);
        foods(k).name = names(k);
        foods(k).category = foodCategories(k);
        foods(k).targetId = lower(foodCategories(k));
    end

    data = struct( ...
        'activityId', "TASTE", ...
        'categories', categories, ...
        'foods', foods);

    ValidateTasteDataset(data);
end
