function data = ColorSortingData()
%COLORSORTINGDATA MATLAB-owned data for the Color Sorting activity.
%
%   The item identifiers and basket identifiers are protocol identifiers.
%   Unity may display them, but only MATLAB stores the correct item-to-color
%   relationship and validates an answer.

    colors = ["Red", "Orange", "Yellow", "Green", "Blue", "Purple"];

    baskets = repmat(struct('id', "", 'color', ""), 1, numel(colors));
    for k = 1:numel(colors)
        baskets(k).id = "basket_" + lower(colors(k));
        baskets(k).color = colors(k);
    end

    itemIds = [ ...
        "apple", ...
        "carrot", ...
        "duck", ...
        "leaf", ...
        "blue_car", ...
        "grapes", ...
        "strawberry", ...
        "basketball", ...
        "star", ...
        "frog", ...
        "balloon", ...
        "butterfly"];

    itemNames = [ ...
        "Apple", ...
        "Carrot", ...
        "Duck", ...
        "Leaf", ...
        "Blue Car", ...
        "Grapes", ...
        "Strawberry", ...
        "Basketball", ...
        "Star", ...
        "Frog", ...
        "Balloon", ...
        "Butterfly"];

    itemColors = [ ...
        "Red", ...
        "Orange", ...
        "Yellow", ...
        "Green", ...
        "Blue", ...
        "Purple", ...
        "Red", ...
        "Orange", ...
        "Yellow", ...
        "Green", ...
        "Blue", ...
        "Purple"];

    items = repmat(struct('id', "", 'name', "", 'color', "", 'basketId', ""), ...
        1, numel(itemIds));
    for k = 1:numel(itemIds)
        items(k).id = itemIds(k);
        items(k).name = itemNames(k);
        items(k).color = itemColors(k);
        items(k).basketId = "basket_" + lower(itemColors(k));
    end

    data = struct( ...
        'activityId', "COLOR", ...
        'colors', colors, ...
        'baskets', baskets, ...
        'items', items);
end
